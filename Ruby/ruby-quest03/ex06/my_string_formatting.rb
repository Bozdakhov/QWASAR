    
def my_string_formatting(firstname, lastname, age)
    puts "Hello, my name is #{firstname} #{lastname}, I'm #{age}."
end
      


# my_string_formatting("john", "doe", 37)  # Output: Hello, my name is john doe, I'm 37.
# my_string_formatting("Baby", "Yoda", 50)  # Output: Hello, my name is Baby Yoda, I'm 50.
