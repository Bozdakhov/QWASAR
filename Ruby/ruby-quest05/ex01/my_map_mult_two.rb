def my_map_mult_two(param_1)
    # Initialize a new array to hold the multiplied values
    multiplied_array = []
    
    # Loop through each element in the array
    for element in param_1
      # Multiply the element by 2 and add it to the new array
      multiplied_array << element * 2
    end
    
    # Return the new array
    return multiplied_array
  end
  